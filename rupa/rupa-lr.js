let isInitialized = false;

function initRupaLr() {
    if (isInitialized) return;
    
    const container = document.getElementById('rupa-lr-content');
    const loading = document.getElementById('rupa-lr-loading');
    
    if (!container) {
        console.error('[rupa-lr.js] rupa-lr-content container not found');
        return;
    }
    
    let html = '';

    // 1. පූර්විකාව සහ සතිපට්ඨාන විවරණය UI එකට එකතු කිරීම
    if (typeof rupaIntroData !== 'undefined') {
        html += `
        <div class="col-span-full bg-gradient-to-r from-amber-900/20 via-slate-800/60 to-amber-900/20 rounded-2xl p-5 md:p-6 border border-amber-500/30 mb-6 shadow-xl">
            <div class="text-center space-y-2 border-b border-amber-500/20 pb-4 mb-4">
                <span class="text-xs uppercase tracking-widest text-amber-400 font-bold">${rupaIntroData.namaskara}</span>
                <h2 class="text-xl md:text-2xl font-bold text-amber-300">${rupaIntroData.title}</h2>
                <p class="text-xs text-slate-300">${rupaIntroData.whyMeditate.suttaSource}</p>
            </div>
            
            <div class="space-y-3 text-xs md:text-sm text-slate-300 leading-relaxed">
                <div class="p-3 bg-slate-900/80 rounded-xl border border-slate-700/60 font-serif text-amber-200">
                    <i class="fa-solid fa-quote-left text-amber-500/50 mr-2"></i>${rupaIntroData.whyMeditate.paliText}
                </div>
                <p>${rupaIntroData.whyMeditate.sinhalaMeaning}</p>
                <p class="text-amber-100/90 bg-amber-950/40 p-3 rounded-lg border border-amber-900/40">${rupaIntroData.whyMeditate.commentaryExplanation}</p>
            </div>
        </div>
        `;
    }
    
    // 2. අටවිසි රූප කාඩ්පත් Render කිරීම
    rupaLrData.forEach((item, index) => {
        const c = colorMap[item.color] || colorMap.amber;
        
        const paliHtml = item.pali.map(line => {
            if (line.match(/^\d+\./)) {
                return `<div class="pali-line-numbered text-amber-300 font-medium">${line}</div>`;
            }
            if (line.startsWith('[')) {
                return `<div class="pali-line-ref text-[11px] text-slate-400 mt-1">${line}</div>`;
            }
            if (line.match(/^\s+\(/)) {
                return `<div class="pali-line-sub text-amber-200/90 pl-3">${line}</div>`;
            }
            return `<div class="pali-line">${line}</div>`;
        }).join('');
        
        html += `
        <div class="rupa-card bg-white dark:bg-slate-800 rounded-2xl shadow-md border ${c.border} overflow-hidden transition-all hover:shadow-lg fade-in flex flex-col justify-between" data-name="${item.name.toLowerCase()}">
            <div>
                <!-- Card Header -->
                <div class="bg-gradient-to-r ${c.header} px-4 py-3">
                    <div class="flex items-center gap-3">
                        <div class="w-9 h-9 rounded-xl bg-white/20 backdrop-blur-sm flex items-center justify-center text-white text-base shrink-0">
                            <i class="fa-solid ${item.icon}"></i>
                        </div>
                        <div class="flex-1 min-w-0">
                            <h3 class="font-bold text-base text-white truncate">${item.name}</h3>
                            <p class="text-[10px] text-white/80">${item.category}</p>
                        </div>
                        <span class="text-[10px] font-bold px-2 py-0.5 rounded-full bg-white/25 text-white border border-white/30">${index + 1}</span>
                    </div>
                </div>
                
                <!-- Card Body - චතුෂ්කය -->
                <div class="p-4 space-y-3 text-xs sm:text-sm">
                    
                    <!-- පාලි පාඨය -->
                    <div class="pali-box bg-slate-900/80 rounded-xl p-3.5 border border-slate-700/60 font-serif">
                        <div class="flex items-center gap-2 mb-2 pb-1.5 border-b border-slate-700/80">
                            <i class="fa-solid fa-language text-amber-400 text-sm"></i>
                            <span class="font-bold text-amber-300 text-xs">පාලි පාඨය</span>
                        </div>
                        <div class="space-y-1">
                            ${paliHtml}
                        </div>
                    </div>
                    
                    <!-- ලක්ඛණ -->
                    <div class="bg-slate-800/40 p-2.5 rounded-xl border border-slate-700/40 space-y-1">
                        <div class="flex items-center gap-1.5 text-amber-400 font-bold text-xs uppercase">
                            <span class="w-1.5 h-1.5 rounded-full bg-amber-400"></span> 1. ලක්ඛණ
                        </div>
                        <p class="text-slate-200 leading-relaxed">${item.lakhana}</p>
                    </div>
                    
                    <!-- රස -->
                    <div class="bg-slate-800/40 p-2.5 rounded-xl border border-slate-700/40 space-y-1">
                        <div class="flex items-center gap-1.5 text-sky-400 font-bold text-xs uppercase">
                            <span class="w-1.5 h-1.5 rounded-full bg-sky-400"></span> 2. රස (කිච්ච/සම්පත්ති)
                        </div>
                        <p class="text-slate-200 leading-relaxed">${item.rasa}</p>
                    </div>
                    
                    <!-- පච්චුපට්ඨාන -->
                    <div class="bg-slate-800/40 p-2.5 rounded-xl border border-slate-700/40 space-y-1">
                        <div class="flex items-center gap-1.5 text-emerald-400 font-bold text-xs uppercase">
                            <span class="w-1.5 h-1.5 rounded-full bg-emerald-400"></span> 3. පච්චුපට්ඨාන
                        </div>
                        <p class="text-slate-200 leading-relaxed">${item.paccupatthana}</p>
                    </div>
                    
                    <!-- පදට්ඨාන -->
                    <div class="bg-slate-800/40 p-2.5 rounded-xl border border-slate-700/40 space-y-1">
                        <div class="flex items-center gap-1.5 text-rose-400 font-bold text-xs uppercase">
                            <span class="w-1.5 h-1.5 rounded-full bg-rose-400"></span> 4. පදට්ඨාන
                        </div>
                        <p class="text-slate-200 leading-relaxed">${item.padatthana}</p>
                    </div>

                    ${item.note ? `
                    <div class="p-2 bg-amber-950/20 rounded-lg border border-amber-900/30 text-[11px] text-amber-200/80">
                        ${item.note}
                    </div>` : ''}

                </div>
            </div>
        </div>
        `;
    });

    // 3. භාවනා ක්‍රමය UI කොටස
    if (typeof rupaBhavanaMethod !== 'undefined') {
        html += `
        <div class="col-span-full bg-slate-900/90 rounded-2xl p-6 border border-emerald-800/50 mt-4 space-y-4 shadow-xl">
            <div class="flex items-center gap-3 border-b border-emerald-900 pb-3">
                <span class="p-2 bg-emerald-950 rounded-lg text-emerald-400 border border-emerald-800">
                    <i class="fa-solid fa-dharmachakra text-lg"></i>
                </span>
                <h3 class="text-lg font-bold text-emerald-300">${rupaBhavanaMethod.title}</h3>
            </div>
            <div class="grid grid-cols-1 md:grid-cols-2 gap-3 text-xs md:text-sm text-slate-300">
                ${rupaBhavanaMethod.instructions.map(inst => `
                    <div class="bg-slate-800/60 p-3 rounded-xl border border-slate-700/50 flex gap-2">
                        <i class="fa-solid fa-check text-emerald-400 text-xs mt-1"></i>
                        <span>${inst}</span>
                    </div>
                `).join('')}
            </div>
            <div class="text-center pt-2">
                <span class="inline-block px-4 py-1.5 bg-slate-800 text-amber-300 font-bold text-xs rounded-full border border-slate-700">
                    ${rupaBhavanaMethod.conclusion}
                </span>
            </div>
        </div>
        `;
    }
    
    container.innerHTML = html;
    if (loading) loading.style.display = 'none';
    isInitialized = true;
    console.log('[rupa-lr.js] රූප 28 සහ ආශ්‍රිත සියලු විවරණ සාර්ථකව load කරන ලදී');
}

// Global Export
window.initRupaLr = initRupaLr;
